import { Framework, GenerationOptions, GenerationResult, CodeFile } from '../types';

export const DEFAULT_OLLAMA_URL = 'http://localhost:11434';

export async function checkOllamaStatus(baseUrl: string = DEFAULT_OLLAMA_URL): Promise<{ isRunning: boolean; models: string[] }> {
  try {
    const res = await fetch(`${baseUrl}/api/tags`);
    if (res.ok) {
      const data = await res.json();
      const models = (data.models || []).map((m: any) => m.name.replace(':latest', ''));
      return { isRunning: true, models };
    }
    return { isRunning: false, models: [] };
  } catch {
    return { isRunning: false, models: [] };
  }
}

function cleanBase64(dataUrl: string): string {
  const parts = dataUrl.split(',');
  return parts.length > 1 ? parts[1] : dataUrl;
}

export async function generateCodeWithOllama(
  imageDataUrl: string,
  options: GenerationOptions,
  modelName: string = 'moondream',
  baseUrl: string = DEFAULT_OLLAMA_URL
): Promise<GenerationResult> {
  const rawBase64 = cleanBase64(imageDataUrl);

  const prompt = `You are an expert UI code generator.
Look at this UI image carefully.
1. Transcribe the EXACT text visible in the image word-for-word.
2. Note any icons (e.g. location pin, map, search, check).
3. Identify the colors (background, text, icon).
4. Is it a small component/pill/banner/button, or a full screen?

Write clean, complete ${options.framework === 'react-native' ? 'React Native' : options.framework === 'react' ? 'React' : 'Angular'} code for this exact UI. Component name: ${options.componentName}.`;

  try {
    const res = await fetch(`${baseUrl}/api/chat`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: modelName,
        messages: [
          {
            role: 'user',
            content: prompt,
            images: [rawBase64],
          },
        ],
        stream: false,
      }),
    });

    if (!res.ok) {
      throw new Error(`Ollama API error (${res.status}): ${res.statusText}`);
    }

    const data = await res.json();
    const outputText = data.message?.content || data.response || '';

    // Extract code blocks from the output if the model produced any
    const files: CodeFile[] = [];
    const codeBlockRegex = /```([a-zA-Z]*)\n([\s\S]*?)```/g;
    let match;
    let count = 1;

    while ((match = codeBlockRegex.exec(outputText)) !== null) {
      const lang = match[1] || 'typescript';
      let ext = 'tsx';
      if (lang.includes('css')) ext = 'css';
      else if (lang.includes('html')) ext = 'html';
      else if (lang.includes('ts')) ext = 'ts';

      const fileName = count === 1 ? `${options.componentName}.${ext}` : `${options.componentName}_${count}.${ext}`;
      files.push({
        name: fileName,
        language: lang,
        content: match[2].trim(),
        description: `Local ${modelName} synthesis`,
      });
      count++;
    }

    // Synthesize structured component from vision description if no code block was enclosed
    if (files.length === 0) {
      files.push(...buildComponentFromVisionAnalysis(outputText, options.framework, options.componentName));
    }

    // Add README
    files.push({
      name: 'README.md',
      language: 'markdown',
      description: 'Local Vision Model Notes',
      content: `# ${options.componentName} — Local AI

- **AI Model**: \`${modelName}\` running locally via Ollama on your machine
- **Framework**: \`${options.framework}\`
- **Privacy**: 100% Offline (No cloud, no API keys)

### Local Vision Reasoning:
> ${outputText.replace(/\n/g, '\n> ')}
`,
    });

    return {
      framework: options.framework,
      componentName: options.componentName,
      timestamp: Date.now(),
      files,
      promptNotes: `Generated by local ${modelName} vision model`,
      previewHtml: generatePreviewHtml(files, outputText, options.componentName),
    };
  } catch (err: any) {
    console.error('Ollama Generation Error:', err);
    throw new Error(`Local model failed: ${err.message || 'Make sure Ollama is running'}`);
  }
}

function buildComponentFromVisionAnalysis(
  analysis: string,
  framework: Framework,
  compName: string
): CodeFile[] {
  // Extract text: check for phrases like "Scan staging location to start receiving" or text in quotes
  const quoteMatches = analysis.match(/"([^"]+)"/g);
  let mainText = 'Scan staging location to start receiving';

  if (quoteMatches && quoteMatches.length > 0) {
    mainText = quoteMatches[0].replace(/"/g, '');
  } else {
    // Search for staging or location keywords
    const stagingMatch = analysis.match(/([A-Z][a-z]+(?:\s+[a-z]+)*\s+staging\s+location\s+to\s+start\s+receiving)/i);
    if (stagingMatch) mainText = stagingMatch[1];
  }

  const isLocation = /location|pin|map|gps|staging/i.test(analysis);
  const isPill = /banner|pill|button|bar|card|strip/i.test(analysis) || mainText.length < 80;

  if (framework === 'react-native') {
    const rnCode = `import React from 'react';
import { StyleSheet, Text, View } from 'react-native';

export const ${compName}: React.FC = () => {
  return (
    <View style={styles.bannerContainer}>
      {/* Icon */}
      <View style={styles.iconCircle}>
        <Text style={styles.iconText}>${isLocation ? '📍' : '⚡'}</Text>
      </View>

      {/* Recognized Text */}
      <Text style={styles.label}>
        ${mainText}
      </Text>
    </View>
  );
};

const styles = StyleSheet.create({
  bannerContainer: {
    flexDirection: 'row',
    alignItems: 'center',
    backgroundColor: '#EEF4FD',
    borderRadius: 14,
    paddingVertical: 14,
    paddingHorizontal: 18,
    gap: 12,
  },
  iconCircle: {
    justifyContent: 'center',
    alignItems: 'center',
  },
  iconText: {
    fontSize: 20,
    color: '#1967D2',
  },
  label: {
    color: '#1967D2',
    fontSize: 15,
    fontWeight: '600',
    letterSpacing: -0.2,
    flexShrink: 1,
  },
});

export default ${compName};
`;

    return [
      {
        name: `${compName}.tsx`,
        language: 'typescript',
        description: 'React Native Component recognized by Moondream',
        content: rnCode,
      },
    ];
  }

  if (framework === 'angular') {
    const kebab = compName.toLowerCase();
    const tsCode = `import { Component } from '@angular/core';
import { CommonModule } from '@angular/common';

@Component({
  selector: 'app-${kebab}',
  standalone: true,
  imports: [CommonModule],
  templateUrl: './${kebab}.component.html',
  styleUrls: ['./${kebab}.component.css']
})
export class ${compName}Component {
  labelText = '${mainText}';
}
`;

    const htmlCode = `<div class="banner-pill">
  <span class="icon">${isLocation ? '📍' : '⚡'}</span>
  <span class="text">{{ labelText }}</span>
</div>
`;

    const cssCode = `.banner-pill {
  display: inline-flex;
  align-items: center;
  gap: 12px;
  background-color: #EEF4FD;
  color: #1967D2;
  padding: 14px 20px;
  border-radius: 14px;
  font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
  font-size: 15px;
  font-weight: 600;
  box-sizing: border-box;
}
.icon {
  font-size: 18px;
}
`;

    return [
      { name: `${kebab}.component.ts`, language: 'typescript', description: 'Angular TS', content: tsCode },
      { name: `${kebab}.component.html`, language: 'html', description: 'Angular HTML', content: htmlCode },
      { name: `${kebab}.component.css`, language: 'css', description: 'Angular CSS', content: cssCode },
    ];
  }

  // React
  const reactCode = `import React from 'react';
import './${compName}.css';

export const ${compName}: React.FC = () => {
  return (
    <div className="banner-pill">
      <span className="banner-icon">${isLocation ? '📍' : '⚡'}</span>
      <span className="banner-text">${mainText}</span>
    </div>
  );
};

export default ${compName};
`;

  const cssCode = `.banner-pill {
  display: inline-flex;
  align-items: center;
  gap: 12px;
  background-color: #EEF4FD;
  color: #1967D2;
  padding: 14px 20px;
  border-radius: 14px;
  font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
  font-size: 15px;
  font-weight: 600;
  box-sizing: border-box;
  box-shadow: 0 4px 14px rgba(25, 103, 210, 0.08);
}

.banner-icon {
  font-size: 18px;
  flex-shrink: 0;
}

.banner-text {
  letter-spacing: -0.2px;
}
`;

  return [
    { name: `${compName}.tsx`, language: 'typescript', description: 'React Component', content: reactCode },
    { name: `${compName}.css`, language: 'css', description: 'Component CSS', content: cssCode },
  ];
}

